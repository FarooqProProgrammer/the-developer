#!/usr/bin/env node
/**
 * Regenerate project folder structure into FOLDER_STRUCTURE.md after each agent chat turn.
 *
 * Events: stop (after chat), sessionEnd (optional cleanup regenerate)
 * Fail-open: never block the agent.
 */
const fs = require('fs');
const path = require('path');

const OUT_NAME = 'FOLDER_STRUCTURE.md';
const SKIP = new Set([
  '.git',
  'node_modules',
  '.next',
  'dist',
  'build',
  'coverage',
  '.turbo',
  '.cache',
  '.codegraph',
  'vendor',
  '.venv',
  'venv',
  '__pycache__',
  '.pytest_cache',
  'Pods',
  'target',
]);
const MAX_DEPTH = 6;
const MAX_ENTRIES = 4000;

function projectRoot() {
  return (
    process.env.CURSOR_PROJECT_DIR ||
    process.env.CLAUDE_PROJECT_DIR ||
    process.cwd()
  );
}

function readStdin() {
  try {
    const raw = fs.readFileSync(0, 'utf8');
    if (!raw.trim()) return {};
    return JSON.parse(raw);
  } catch {
    return {};
  }
}

function writeJson(obj) {
  process.stdout.write(JSON.stringify(obj));
}

function shouldSkipName(name) {
  if (SKIP.has(name)) return true;
  if (name === 'FOLDER_STRUCTURE.md') return true;
  return false;
}

function walk(dir, prefix, depth, lines, state) {
  if (depth > MAX_DEPTH || state.count >= MAX_ENTRIES) return;
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }

  entries.sort((a, b) => {
    if (a.isDirectory() !== b.isDirectory()) return a.isDirectory() ? -1 : 1;
    return a.name.localeCompare(b.name);
  });

  for (const ent of entries) {
    if (state.count >= MAX_ENTRIES) {
      lines.push(`${prefix}… (truncated at ${MAX_ENTRIES} entries)`);
      return;
    }
    if (shouldSkipName(ent.name)) continue;
    if (ent.name.startsWith('.') && ent.name !== '.cursor' && ent.name !== '.specify' && ent.name !== '.cursor-plugin') {
      // keep useful dotfolders; skip other hidden
      if (!['.github', '.vscode', '.husky'].includes(ent.name)) continue;
    }

    const full = path.join(dir, ent.name);
    const isDir = ent.isDirectory();
    lines.push(`${prefix}${isDir ? ent.name + '/' : ent.name}`);
    state.count += 1;

    if (isDir) {
      walk(full, prefix + '  ', depth + 1, lines, state);
    }
  }
}

function regenerate(root) {
  const lines = [];
  const state = { count: 0 };
  const generated = new Date().toISOString();

  lines.push('# Folder structure');
  lines.push('');
  lines.push(`Generated: ${generated}`);
  lines.push(`Root: \`${path.basename(root)}\``);
  lines.push('');
  lines.push('```');
  lines.push(path.basename(root) + '/');
  walk(root, '  ', 0, lines, state);
  lines.push('```');
  lines.push('');
  lines.push('_Auto-regenerated by `stop` / `sessionEnd` hook `regenerate-folder-structure.js`. Skips node_modules, .git, vendor, build caches._');
  lines.push('');

  const outPath = path.join(root, OUT_NAME);
  fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
  return outPath;
}

function main() {
  const input = readStdin();
  const event = input.hook_event_name || '';
  if (event && event !== 'stop' && event !== 'sessionEnd') {
    writeJson({});
    return;
  }

  try {
    regenerate(projectRoot());
  } catch {
    // fail-open
  }
  writeJson({});
}

try {
  main();
} catch {
  writeJson({});
  process.exit(0);
}
